ARDOS_PARTNER_BASE_URL=
ARDOS_PARTNER_TOKEN=
ENV

docker compose up -d --build
docker compose ps
curl -fsS http://localhost:5020/health/live
curl -fsS http://localhost:5020/flight-data/health/ready
curl -fsS http://localhost:5020/situation-data/health/ready
