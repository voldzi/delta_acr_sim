export function readInitialUiLanguage(): UiLanguage {
  if (typeof window === "undefined") {
    return "cs";
  }
  const storedLanguage = window.localStorage.getItem(uiLanguageStorageKey);
  if (storedLanguage === "cs" || storedLanguage === "en") {
    return storedLanguage;
  }
  return window.navigator.language.toLowerCase().startsWith("cs") ? "cs" : "en";
}

export function storeUiLanguage(language: UiLanguage): void {
  if (typeof window === "undefined") {
    return;
  }
  window.localStorage.setItem(uiLanguageStorageKey, language);
}

export function translateUi(language: UiLanguage, source: string): string {
  if (language !== "cs") {
    return source;
  }
  return csTranslations[source] ?? source;
}
